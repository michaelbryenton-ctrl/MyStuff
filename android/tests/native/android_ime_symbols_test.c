#include "sdl3/common.h"
#include "xroar.h"

struct xroar xroar;
struct hkbd hkbd;
event_ticks event_current_tick;
static unsigned fallback_presses, fallback_releases;

/* Host-key events are stubbed; the actual queue, SDL Android dispatch,
 * Unicode mapping and machine keyboard matrix are used below. */
void hk_scan_press(uint8_t code) {
    fallback_presses++;
    if (code == SDL_SCANCODE_LSHIFT || code == SDL_SCANCODE_RSHIFT) {
        hkbd.state |= HK_MASK_SHIFT;
        keyboard_press(xroar.keyboard_interface, DSCAN_SHIFT);
    } else if (code >= SDL_SCANCODE_A && code <= SDL_SCANCODE_Z) {
        keyboard_press(xroar.keyboard_interface, DSCAN_A + code - SDL_SCANCODE_A);
    } else if (code == SDL_SCANCODE_RETURN) {
        keyboard_press(xroar.keyboard_interface, DSCAN_ENTER);
    }
}
void hk_scan_release(uint8_t code) {
    fallback_releases++;
    if (code == SDL_SCANCODE_LSHIFT || code == SDL_SCANCODE_RSHIFT) {
        hkbd.state &= ~HK_MASK_SHIFT;
        keyboard_release(xroar.keyboard_interface, DSCAN_SHIFT);
    } else if (code >= SDL_SCANCODE_A && code <= SDL_SCANCODE_Z) {
        keyboard_release(xroar.keyboard_interface, DSCAN_A + code - SDL_SCANCODE_A);
    } else if (code == SDL_SCANCODE_RETURN) {
        keyboard_release(xroar.keyboard_interface, DSCAN_ENTER);
    }
}
bool SDL_HideCursor(void) { return true; }
bool SDL_ShowSimpleMessageBox(SDL_MessageBoxFlags flags, const char *title,
        const char *message, SDL_Window *window) {
    (void)flags; (void)title; (void)message; (void)window;
    return true;
}
static bool pressed(int key) {
    struct keyboard_interface *ki = xroar.keyboard_interface;
    int col = ki->keymap.point[key].col, row = ki->keymap.point[key].row;
    return !(ki->keyboard_column[col] & (1u << row));
}
static void neutral(void) {
    for (int i = 0; i < 8; i++) assert(xroar.keyboard_interface->keyboard_column[i] == ~0u);
}
static void process(struct ui_sdl3_interface *ui, unsigned time) {
    event_current_tick = time;
    sdl_process_textinput(ui);
}
static void virtual_key(struct ui_sdl3_interface *ui, SDL_Scancode code, bool down) {
    SDL_KeyboardEvent event = {0};
    event.scancode = code;
    if (down) sdl_keypress(ui, &event);
    else sdl_keyrelease(ui, &event);
}
static void virtual_quote(struct ui_sdl3_interface *ui) {
    virtual_key(ui, SDL_SCANCODE_LSHIFT, true);
    virtual_key(ui, SDL_SCANCODE_APOSTROPHE, true);
    virtual_key(ui, SDL_SCANCODE_APOSTROPHE, false);
    virtual_key(ui, SDL_SCANCODE_LSHIFT, false);
}
int main(void) {
    assert(android_ime_symbol(SDL_SCANCODE_APOSTROPHE, true) == '"');
    assert(android_ime_symbol(SDL_SCANCODE_APOSTROPHE, false) == '\'');
    assert(android_ime_symbol(SDL_SCANCODE_2, true) == '@');
    assert(android_ime_symbol(SDL_SCANCODE_SEMICOLON, true) == ':');
    assert(android_ime_symbol(SDL_SCANCODE_EQUALS, true) == '+');
    assert(android_ime_symbol(SDL_SCANCODE_MINUS, false) == '-');
    assert(android_ime_symbol(SDL_SCANCODE_9, true) == '(');
    assert(android_ime_symbol(SDL_SCANCODE_0, true) == ')');
    assert(android_ime_symbol(SDL_SCANCODE_A, false) == 0);
    assert(android_ime_symbol(SDL_SCANCODE_RETURN, false) == 0);
    assert(android_ime_symbol(SDL_SCANCODE_2, false) == 0);

    for (int layout = 0; layout < dkbd_num_layouts; layout++) {
        struct ui_sdl3_interface ui = {0};
        struct keyboard_interface *ki = keyboard_interface_new();
        xroar.keyboard_interface = ki;
        keyboard_set_keymap(ki, layout);
        memset(&hkbd, 0, sizeof(hkbd));
        android_ime_queue_init(&ui.ime_keys, 50, 30);
        event_current_tick = 0;
        virtual_quote(&ui); /* Same pairs generated by SDL's Android IME. */
        process(&ui, 0);
        assert(pressed(DSCAN_SHIFT) && pressed(DSCAN_2));
        process(&ui, 49);
        assert(pressed(DSCAN_SHIFT) && pressed(DSCAN_2));
        process(&ui, 50);
        neutral();
        assert(hkbd.state == 0 && ui.ime_unicode[SDL_SCANCODE_APOSTROPHE] == 0);

        /* Dedicated button uses the identical timed path; repeated quotes release. */
        event_current_tick = 100;
        sdl_tap_key(&ui, SDL_SCANCODE_APOSTROPHE);
        sdl_tap_key(&ui, SDL_SCANCODE_APOSTROPHE);
        virtual_key(&ui, SDL_SCANCODE_A, true);
        virtual_key(&ui, SDL_SCANCODE_A, false);
        process(&ui, 100);
        assert(pressed(DSCAN_SHIFT) && pressed(DSCAN_2));
        process(&ui, 150);
        neutral();
        process(&ui, 180);
        assert(pressed(DSCAN_SHIFT) && pressed(DSCAN_2));
        process(&ui, 230);
        neutral();
        process(&ui, 260);
        assert(pressed(DSCAN_A) && !pressed(DSCAN_SHIFT));
        process(&ui, 310);
        neutral();

        /* Focus loss releases both a translated symbol and its synthetic Shift. */
        event_current_tick = 400;
        sdl_tap_key(&ui, SDL_SCANCODE_APOSTROPHE);
        process(&ui, 400);
        sdl_cancel_textinput(&ui);
        neutral();
        assert(hkbd.state == 0 && ui.ime_keys.count == 0);

        /* US virtual punctuation must not depend on an ISO physical layout. */
        hkbd.layout = hk_layout_iso;
        event_current_tick = 500;
        virtual_key(&ui, SDL_SCANCODE_SEMICOLON, true);
        virtual_key(&ui, SDL_SCANCODE_SEMICOLON, false);
        process(&ui, 500);
        assert(pressed(ki->keymap.unicode_to_dkey[';'].dk_key));
        assert(pressed(DSCAN_SHIFT)
                == ((ki->keymap.unicode_to_dkey[';'].dk_mod & DK_MOD_SHIFT) != 0));
        process(&ui, 550);
        neutral();

        /* Committed ASCII is not typed a second time. */
        sdl_textinput(&ui, "CSAVE \"TEST\"");
        assert(ui.ime_keys.count == 0);
        unsigned before = fallback_presses;
        SDL_KeyboardEvent physical = {0};
        physical.which = 3;
        physical.raw = 75;
        physical.scancode = SDL_SCANCODE_APOSTROPHE;
        sdl_keypress(&ui, &physical);
        sdl_keyrelease(&ui, &physical);
        assert(fallback_presses == before + 1 && ui.ime_keys.count == 0);
        keyboard_interface_free(ki);
    }
    printf("PASS: phone punctuation, timed quote button, repeated quotes, focus reset, "
            "physical-key isolation and ASCII deduplication across %d machine layouts\n",
            dkbd_num_layouts);
}
